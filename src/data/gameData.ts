/** Every gold-costing building also produces a little more. */
const boostGoldBuildings = (state: GameState, mult: number) => {
  for (const building of buildingsData) {
    if (building.costRes === 'gold') {
      state.buildingMultipliers[building.id] = (state.buildingMultipliers[building.id] ?? 1) * mult;
    }
  }
};

/** Doubles every building that yields `resource`. */
const boostResourceBuildings = (state: GameState, resource: ResourceType, mult: number) => {
  for (const building of buildingsData) {
    if ((building.yield[resource] ?? 0) > 0) {
      state.buildingMultipliers[building.id] = (state.buildingMultipliers[building.id] ?? 1) * mult;
    }
  }
};

